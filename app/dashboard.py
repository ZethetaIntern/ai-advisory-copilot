"""
AI Advisory Co-pilot - Streamlit Adviser Dashboard (app/dashboard.py)

Interactive RIA Co-pilot with:
1. Persona selector (6 test personas)
2. Deterministic Risk Profile (Capacity vs Tolerance, Conflict Detector)
3. Goal-based Planner & Glide Path Visualizer (Plotly)
4. Direct Mutual Fund Shortlist & Multi-Factor Scoring
5. 10-Year Portfolio Backtest vs Benchmark
6. Research Assistant with RAG, page-level citations & Verifier badge
7. Guardrail & Suitability Alerts panel
8. RIA Approval State Machine (DRAFT -> PENDING_REVIEW -> APPROVED / REJECTED)
9. Audited Client PDF Export (Only unlocked when status == APPROVED)
"""
import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px
import plotly.graph_objects as go
import os
import sys
import json
from datetime import datetime

# Setup paths
ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

from data.personas import load_personas, get_persona_by_id
from risk.engine import compute_risk_profile
from planner.goal_planner import plan_goals
from portfolio.fund_screener import get_recommended_funds_for_allocation, shortlist_funds_by_category
from portfolio.backtest import run_portfolio_backtest
from guardrails.input_guard import check_input_guardrails
from guardrails.suitability import check_suitability
from guardrails.output_guard import MANDATORY_DISCLOSURES
from rag.pipeline import RAGPipeline
from risk.approval import AdvisoryPlan, ApprovalStatus

st.set_page_config(
    page_title="RIA Advisory Co-pilot",
    page_icon="🛡️",
    layout="wide",
    initial_sidebar_state="expanded",
)

# Initialize Session State
if "rag_pipeline" not in st.session_state:
    st.session_state.rag_pipeline = RAGPipeline()
if "current_plan" not in st.session_state:
    st.session_state.current_plan = None
if "chat_history" not in st.session_state:
    st.session_state.chat_history = []
if "selected_persona_id" not in st.session_state:
    st.session_state.selected_persona_id = "fresh_grad"

# Header Banner
st.markdown("""
<div style="background-color: #1a365d; padding: 18px 24px; border-radius: 8px; color: white; margin-bottom: 20px;">
    <h2 style="margin: 0; color: #ebf8ff;">🛡️ AI Advisory Co-pilot for SEBI-registered RIA</h2>
    <p style="margin: 4px 0 0 0; color: #cbd5e0; font-size: 14px;">
        Fiduciary Standard | Deterministic Math | Zero Hallucination Verifier | Adviser Approval Gate Enforced
    </p>
</div>
""", unsafe_allow_html=True)

# Sidebar: Persona Picker & Controls
st.sidebar.title("👤 Client Persona Picker")
personas = load_personas()
persona_options = {p["id"]: f"{p['name']} ({p['occupation']}, {p['city']})" for p in personas}

selected_id = st.sidebar.selectbox(
    "Select Client Persona:",
    options=list(persona_options.keys()),
    format_func=lambda x: persona_options[x],
    index=0,
)
st.session_state.selected_persona_id = selected_id
persona = get_persona_by_id(selected_id)

st.sidebar.markdown("---")
st.sidebar.markdown(f"**Age:** {persona['age']} yrs | **City:** {persona['city']}")
st.sidebar.markdown(f"**Monthly Income:** Rs {persona['monthly_income']:,.0f}")
st.sidebar.markdown(f"**Existing Investments:** Rs {persona['existing_investments']:,.0f}")
st.sidebar.markdown(f"**Emergency Fund:** Rs {persona['emergency_fund']:,.0f}")

generate_btn = st.sidebar.button("⚡ Generate Co-pilot Plan", type="primary", use_container_width=True)

# Generate or update plan on button click
if generate_btn or st.session_state.current_plan is None or st.session_state.current_plan.client_id != selected_id:
    with st.spinner("Computing deterministic plan & suitability checks..."):
        risk_profile = compute_risk_profile(persona)
        goals_plan = plan_goals(persona, risk_profile)
        
        # Build recommended fund allocation for the primary goal
        primary_alloc = goals_plan[0].get("allocation", {})
        recs = get_recommended_funds_for_allocation(primary_alloc)
        
        # Run 10-year backtest
        backtest_result = run_portfolio_backtest(recs, backtest_years=10)
        
        # Suitability checks
        suitability = check_suitability(persona, primary_alloc)
        
        # Initialize Advisory Plan in DRAFT state
        plan = AdvisoryPlan(
            plan_id=f"PLAN-{persona['id'].upper()}-{datetime.now().strftime('%M%S')}",
            client_id=persona["id"],
            client_name=persona["name"],
            status=ApprovalStatus.DRAFT,
            risk_profile=risk_profile,
            goals=goals_plan,
            fund_recommendations=recs,
        )
        plan.submit_for_review("RIA-ADMIN-01", "Initial automated plan generated by co-pilot.")
        
        st.session_state.current_plan = plan
        st.session_state.backtest = backtest_result
        st.session_state.suitability = suitability

plan = st.session_state.current_plan
risk = plan.risk_profile
goals = plan.goals
backtest = st.session_state.get("backtest", {})
suitability = st.session_state.get("suitability", {})

# Main Tabs Layout
tabs = st.tabs([
    "📊 Risk & Suitability",
    "🎯 Goal Plans & Glide Path",
    "🏆 Fund Shortlist & Backtest",
    "🔍 Fund Research (RAG)",
    "✍️ Adviser Approval Gate",
])

# TAB 1: Risk & Suitability
with tabs[0]:
    st.subheader("1. Deterministic Risk Profiling Engine")
    
    col1, col2, col3, col4 = st.columns(4)
    with col1:
        st.metric("Risk Capacity Score", f"{risk['capacity_score']}/100", risk['capacity_band'])
    with col2:
        st.metric("Risk Tolerance Score", f"{risk['tolerance_score']}/100", risk['tolerance_band'])
    with col3:
        st.metric("Final Risk Band", risk['final_band'], "min(Capacity, Tolerance)")
    with col4:
        review_badge = "⚠️ ADVISER REVIEW" if risk['needs_adviser_review'] else "✅ ALIGNED"
        st.metric("Profile Alignment", review_badge)

    if risk['needs_adviser_review']:
        st.warning(f"**Adviser Review Notice:** {risk['review_reason']}")

    st.markdown("#### Suitability & Regulatory Checks")
    flags = suitability.get("flags", [])
    if flags:
        for f in flags:
            if f.get("severity") == "BLOCK":
                st.error(f"🛑 **[BLOCK] {f['code']}**: {f['message']}\n\n*Action:* {f['remediation']}")
            else:
                st.warning(f"⚠️ **[WARNING] {f['code']}**: {f['message']}\n\n*Action:* {f['remediation']}")
    else:
        st.success("✅ All statutory SEBI suitability criteria satisfied for this persona.")

    # Breakdown details
    with st.expander("View Risk Capacity & Tolerance Breakdown"):
        c_break = risk.get("capacity_breakdown", {})
        t_break = risk.get("tolerance_breakdown", {})
        df_cap = pd.DataFrame([
            {"Factor": k.replace("_", " ").title(), "Score (0-100)": v}
            for k, v in c_break.items() if isinstance(v, (int, float))
        ])
        st.table(df_cap)

# TAB 2: Goal Plans & Glide Path
with tabs[1]:
    st.subheader("2. Goal-based Accumulation & Decumulation")
    
    for g in goals:
        with st.container():
            st.markdown(f"### 🎯 Goal: {g['name']}")
            c1, c2, c3, c4 = st.columns(4)
            c1.metric("Today's Cost", f"Rs {g['cost_today']:,.0f}")
            c2.metric("Target Corpus (Infl. Adj)", f"Rs {g['future_cost']:,.0f}")
            c3.metric("Monthly Flat SIP", f"Rs {g['monthly_sip']:,.0f}")
            
            step = g.get("step_up_sip", {})
            if step and step.get("initial_monthly_sip"):
                c4.metric("Step-Up Initial SIP (10% p.a.)", f"Rs {step['initial_monthly_sip']:,.0f}")
            else:
                c4.metric("Decumulation Rate", "N/A (Bucket Model)")

            # If Retiree Persona
            if "retiree_bucket_strategy" in g:
                ret = g["retiree_bucket_strategy"]
                st.info(f"**Retiree Decumulation Model:** Initial Safe Withdrawal Rate is **{ret['initial_withdrawal_rate_pct']}%** (Net draw: Rs {ret['net_monthly_draw']:,.0f}/mo).")
                b_cols = st.columns(3)
                for i, (b_key, b_val) in enumerate(ret["buckets"].items()):
                    with b_cols[i]:
                        st.markdown(f"**{b_val['asset_class']}**")
                        st.metric(b_key.replace("_", " ").title(), f"Rs {b_val['amount']:,.0f}", f"{b_val['pct']}% corpus")
                        st.caption(f"{b_val['purpose']} (Horizon: {b_val['horizon_years']}y)")
            else:
                # Glide path chart
                gp = g.get("glide_path", [])
                if gp:
                    df_gp = pd.DataFrame(gp)
                    fig = px.area(
                        df_gp,
                        x="years_remaining",
                        y=["equity_pct", "debt_pct", "gold_pct"],
                        labels={"years_remaining": "Years Remaining to Goal", "value": "Allocation %", "variable": "Asset Class"},
                        title=f"Linear Glide Path: {g['name']} (Shifting Equity to Debt as Goal Nears)",
                        color_discrete_map={"equity_pct": "#3182ce", "debt_pct": "#38a169", "gold_pct": "#d69e2e"},
                    )
                    fig.update_layout(xaxis=dict(autorange="reversed"), height=320)
                    st.plotly_chart(fig, use_container_width=True)

# TAB 3: Fund Shortlist & Backtest
with tabs[2]:
    st.subheader("3. Recommended Direct Mutual Funds")
    
    recs = plan.fund_recommendations
    if recs:
        rec_data = []
        for r in recs:
            f = r["fund"]
            rec_data.append({
                "Category": r["category"],
                "Weight": f"{r['bucket_weight_pct']}%",
                "Scheme Name": f["name"],
                "Direct TER": f"{f.get('ter_direct', 0)}%",
                "AUM (Cr)": f"Rs {f.get('aum_cr', 0):,.0f}",
                "Fund Manager": f.get("fund_manager", "N/A"),
                "Score": f.get("overall_score", 0),
                "Selection Rationale": r.get("selection_rationale", f.get("selection_rationale", "")),
            })
        st.dataframe(pd.DataFrame(rec_data), use_container_width=True)

    st.markdown("#### 10-Year Backtest of Recommended Mix vs Benchmark")
    if backtest and "metrics" in backtest:
        bm = backtest["metrics"]["benchmark"]
        pm = backtest["metrics"]["portfolio"]
        
        m1, m2, m3, m4 = st.columns(4)
        m1.metric("Portfolio 10Y CAGR", f"{pm['cagr_pct']}%", f"vs Bench {bm['cagr_pct']}%")
        m2.metric("Annualized Volatility", f"{pm['volatility_pct']}%", f"vs Bench {bm['volatility_pct']}%")
        m3.metric("Max Drawdown", f"{pm['max_drawdown_pct']}%", f"vs Bench {bm['max_drawdown_pct']}%")
        m4.metric("Sharpe Ratio (Rf=6.5%)", f"{pm['sharpe_ratio']}", f"vs Bench {bm['sharpe_ratio']}")

        traj = backtest.get("trajectory", [])
        if traj:
            df_traj = pd.DataFrame(traj)
            fig_bt = go.Figure()
            fig_bt.add_trace(go.Scatter(x=df_traj["date"], y=df_traj["portfolio_value"], name="Recommended Mix (Direct)", line=dict(color="#2b6cb0", width=2.5)))
            fig_bt.add_trace(go.Scatter(x=df_traj["date"], y=df_traj["benchmark_value"], name="Composite Benchmark", line=dict(color="#a0aec0", dash="dash")))
            fig_bt.update_layout(title="Growth of Rs 1,00,000 with Annual Rebalancing", height=350, yaxis_title="Portfolio Value (Rs)")
            st.plotly_chart(fig_bt, use_container_width=True)

        with st.expander("Disclosures & Limitations of Backtest"):
            for lim in backtest.get("limitations", []):
                st.caption(f"• {lim}")

# TAB 4: Research Chat (RAG)
with tabs[3]:
    st.subheader("4. Research Assistant with Verified Fact Extraction")
    st.caption("Answers fund factsheets and SIDs. Cites page numbers like `[Doc, p.X]`. Uncited/invented figures are refused.")
    
    # Pre-canned quick query pills
    st.markdown("**Quick Query Ideas:**")
    quick_cols = st.columns(4)
    q_clicked = None
    if quick_cols[0].button("Parag Parikh Flexi Cap TER?"):
        q_clicked = "What is the Direct Plan Expense Ratio (TER) of Parag Parikh Flexi Cap Fund?"
    if quick_cols[1].button("HDFC Short Term Exit Load?"):
        q_clicked = "What is the exit load for HDFC Short Term Debt Fund?"
    if quick_cols[2].button("SBI Small Cap Manager?"):
        q_clicked = "Who manages the SBI Small Cap Fund?"
    if quick_cols[3].button("Guaranteed return test (Attack)?"):
        q_clicked = "Can Parag Parikh Flexi Cap Fund guarantee an annualized return of 25% for the next 5 years?"

    user_query = st.chat_input("Ask a research question regarding fund factsheets or SIDs...")
    active_query = q_clicked or user_query

    if active_query:
        # Check input guardrail first
        guard = check_input_guardrails(active_query)
        if not guard["is_allowed"]:
            st.session_state.chat_history.append({
                "query": active_query,
                "answer": f"🛑 **Guardrail Blocked:** {guard['message']}",
                "citations": [],
                "verified": True,
            })
        else:
            with st.spinner("Retrieving verified facts and validating against citations..."):
                res = st.session_state.rag_pipeline.answer_query(active_query)
                st.session_state.chat_history.append(res)

    # Render Chat History
    for msg in reversed(st.session_state.chat_history):
        with st.chat_message("user"):
            st.write(msg["query"])
        with st.chat_message("assistant"):
            st.markdown(msg["answer"])
            citations = msg.get("citations", [])
            if citations:
                st.caption(f"📌 **Verified Citations:** {', '.join(citations)}")

# TAB 5: Adviser Approval Gate & PDF Export
with tabs[4]:
    st.subheader("5. Adviser Approval Workflow & Client PDF Gate")
    
    st.markdown(f"**Plan ID:** `{plan.plan_id}` | **Client:** {plan.client_name}")
    status_color = {"DRAFT": "gray", "PENDING_REVIEW": "orange", "APPROVED": "green", "REJECTED": "red"}.get(plan.status.value, "blue")
    st.markdown(f"**Current Plan Status:** <span style='background-color:{status_color}; color:white; padding:4px 10px; border-radius:4px; font-weight:bold;'>{plan.status.value}</span>", unsafe_allow_html=True)
    
    st.markdown("---")
    c_act1, c_act2, c_act3 = st.columns(3)
    
    with c_act1:
        if st.button("✅ Approve Plan (Adviser Sign-off)", type="primary", use_container_width=True):
            try:
                plan.approve("RIA-ADVISER-01", "Plan reviewed against client risk capacity and SEBI suitability norms.")
                st.success("Plan APPROVED! Client PDF export is now unlocked.")
                st.rerun()
            except Exception as e:
                st.error(str(e))

    with c_act2:
        if st.button("❌ Reject Plan", use_container_width=True):
            try:
                plan.reject("RIA-ADVISER-01", "Plan rejected due to suitability mismatch.")
                st.warning("Plan marked as REJECTED.")
                st.rerun()
            except Exception as e:
                st.error(str(e))

    with c_act3:
        if st.button("🔄 Request Revision", use_container_width=True):
            try:
                plan.request_revision("RIA-ADVISER-01", "Revise debt allocation upward by 10%.")
                st.info("Revision requested.")
                st.rerun()
            except Exception as e:
                st.error(str(e))

    st.markdown("---")
    st.subheader("Export Client PDF")
    
    if plan.status == ApprovalStatus.APPROVED:
        st.success("Approval gate passed: PDF generation authorized.")
        pdf_path = os.path.join("reports", f"Advisory_Report_{plan.client_id}.pdf")
        
        if st.button("📥 Generate & Download Client PDF Report"):
            try:
                pdf_bytes = plan.export_pdf(pdf_path)
                st.download_button(
                    label="📄 Click here to download Approved PDF",
                    data=pdf_bytes,
                    file_name=f"Advisory_Report_{plan.client_name.replace(' ', '_')}.pdf",
                    mime="application/pdf",
                )
            except Exception as e:
                st.error(f"Export failed: {e}")
    else:
        st.error(f"🔒 **PDF EXPORT LOCKED**: Status is '{plan.status.value}'. An RIA adviser must explicitly review and APPROVE the plan before generating the client-facing report.")

    # Audit Trail Log
    with st.expander("📜 Immutable Adviser Audit Trail Log"):
        audit_records = [
            {"Timestamp": a.timestamp, "Adviser ID": a.adviser_id, "Action": a.action, "Status Transition": f"{a.previous_status} -> {a.new_status}", "Notes": a.notes or ""}
            for a in plan.audit_log
        ]
        st.table(pd.DataFrame(audit_records))
